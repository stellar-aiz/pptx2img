"""Independent fixture for theme background references, pattern fills, group fills, and
picture fills on shapes. Everything is drawn here; no source-document assets.

Page 1: the master background is a theme reference (`p:bgRef idx="1001"`) with a tinted
accent color, and six rectangles use pattern presets.
Page 2: a solid-filled group whose children use `a:grpFill` (including a nested group
that passes the fill on), and an ellipse and a rounded rectangle with a stretched
picture fill generated by Pillow.
"""
from io import BytesIO
from pathlib import Path
import sys

from PIL import Image, ImageDraw
from pptx import Presentation
from pptx.enum.shapes import MSO_SHAPE
from pptx.oxml import parse_xml
from pptx.util import Inches

A = 'http://schemas.openxmlformats.org/drawingml/2006/main'
P = 'http://schemas.openxmlformats.org/presentationml/2006/main'
R = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'
NS = f'xmlns:a="{A}" xmlns:p="{P}" xmlns:r="{R}"'
PATTERNS = ['dkUpDiag', 'trellis', 'ltUpDiag', 'horz', 'cross', 'pct50']


def plain(shape):
    """Drop python-pptx's text body, theme style, and line so only the fill is drawn."""
    el = shape._element
    el.remove(el.txBody)
    style = el.find(f'{{{P}}}style')
    if style is not None:
        el.remove(style)
    el.spPr.append(parse_xml(f'<a:ln {NS}><a:noFill/></a:ln>'))
    return shape


def fill(shape, xml):
    sp_pr = shape._element.spPr
    sp_pr.insert(len(sp_pr) - 1, parse_xml(xml))


def picture():
    image = Image.new('RGB', (240, 160), (36, 90, 81))
    draw = ImageDraw.Draw(image)
    for i in range(0, 240, 40):
        draw.rectangle([i, 0, i + 19, 159], fill=(210, 237, 254))
    draw.ellipse([80, 40, 160, 120], fill=(192, 0, 0))
    out = BytesIO()
    image.save(out, 'PNG')
    out.seek(0)
    return out


def main(out):
    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(10), Inches(5.625)
    master = prs.slide_masters[0]._element
    c_sld = master.find(f'{{{P}}}cSld')
    old = c_sld.find(f'{{{P}}}bg')
    if old is not None:
        c_sld.remove(old)
    c_sld.insert(0, parse_xml(
        f'<p:bg {NS}><p:bgRef idx="1001"><a:schemeClr val="accent1">'
        '<a:lumMod val="20000"/><a:lumOff val="80000"/></a:schemeClr></p:bgRef></p:bg>'))

    slide = prs.slides.add_slide(prs.slide_layouts[6])
    for i, preset in enumerate(PATTERNS):
        shape = plain(slide.shapes.add_shape(
            MSO_SHAPE.RECTANGLE, Inches(.4 + (i % 3) * 3.15), Inches(.4 + (i // 3) * 2.5),
            Inches(2.8), Inches(2.1)))
        fill(shape, f'<a:pattFill {NS} prst="{preset}"><a:fgClr><a:srgbClr val="245A51"/></a:fgClr>'
                    '<a:bgClr><a:srgbClr val="FFFFFF"/></a:bgClr></a:pattFill>')

    slide = prs.slides.add_slide(prs.slide_layouts[6])
    group = slide.shapes.add_group_shape()
    for i in range(3):
        child = plain(group.shapes.add_shape(
            MSO_SHAPE.ROUNDED_RECTANGLE, Inches(.4), Inches(.4 + i * 1.6), Inches(3.6), Inches(1.3)))
        fill(child, f'<a:grpFill {NS}/>')
    inner = group.shapes.add_group_shape()
    nested = plain(inner.shapes.add_shape(
        MSO_SHAPE.OVAL, Inches(4.3), Inches(.4), Inches(1.3), Inches(1.3)))
    fill(nested, f'<a:grpFill {NS}/>')
    inner._element.grpSpPr.append(parse_xml(f'<a:grpFill {NS}/>'))
    group._element.grpSpPr.append(parse_xml(
        f'<a:solidFill {NS}><a:srgbClr val="C37B49"/></a:solidFill>'))
    _, rid = slide.part.get_or_add_image_part(picture())
    for kind, x in [(MSO_SHAPE.OVAL, 4.3), (MSO_SHAPE.ROUNDED_RECTANGLE, 6.9)]:
        shape = plain(slide.shapes.add_shape(kind, Inches(x), Inches(2.2), Inches(2.6), Inches(2.8)))
        fill(shape, f'<a:blipFill {NS} rotWithShape="1"><a:blip r:embed="{rid}"/>'
                    '<a:stretch><a:fillRect/></a:stretch></a:blipFill>')
    prs.save(out)


if __name__ == '__main__':
    main(Path(sys.argv[1]))
